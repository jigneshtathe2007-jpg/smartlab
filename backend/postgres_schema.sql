CREATE TABLE IF NOT EXISTS students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfid_uid TEXT UNIQUE,
    roll_no TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL,
    department TEXT,
    year_sem TEXT,
    phone TEXT,
    email TEXT,
    created_at TEXT DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS components (
    component_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rfid_uid TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    category TEXT,
    description TEXT,
    shelf_location TEXT,
    status TEXT NOT NULL DEFAULT 'AVAILABLE'
        CHECK (status IN ('AVAILABLE', 'ISSUED', 'DAMAGED', 'LOST')),
    added_at TEXT DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS issues (
    issue_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    component_id BIGINT NOT NULL REFERENCES components(component_id),
    student_id BIGINT NOT NULL REFERENCES students(student_id),
    purpose TEXT,
    issue_date TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP::text),
    expected_return_date TEXT NOT NULL,
    actual_return_date TEXT,
    returned INTEGER NOT NULL DEFAULT 0 CHECK (returned IN (0, 1)),
    remarks TEXT
);

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('admin', 'student')),
    student_id BIGINT UNIQUE REFERENCES students(student_id),
    created_at TEXT DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE TABLE IF NOT EXISTS activity_logs (
    activity_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT,
    actor_name TEXT NOT NULL,
    actor_username TEXT NOT NULL,
    actor_role TEXT NOT NULL,
    action TEXT NOT NULL,
    entity_type TEXT NOT NULL,
    entity_id BIGINT,
    entity_name TEXT NOT NULL,
    created_at TEXT DEFAULT (CURRENT_TIMESTAMP::text)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_users_username_lower ON users (LOWER(username));
CREATE INDEX IF NOT EXISTS idx_issues_component ON issues(component_id, returned);
CREATE INDEX IF NOT EXISTS idx_issues_student ON issues(student_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_issues_one_open_per_component
    ON issues(component_id) WHERE returned = 0;
CREATE INDEX IF NOT EXISTS idx_issues_returned_due
    ON issues(returned, expected_return_date);
CREATE INDEX IF NOT EXISTS idx_activity_logs_created
    ON activity_logs(created_at, activity_id);

CREATE OR REPLACE VIEW current_status AS
SELECT c.component_id, c.rfid_uid, c.name, c.status,
       s.full_name AS issued_to, s.roll_no, i.expected_return_date
FROM components c
LEFT JOIN issues i ON i.component_id = c.component_id AND i.returned = 0
LEFT JOIN students s ON s.student_id = i.student_id;
